/**
 * Check if a role or custom staff permissions grant a specific permission
 */
export function hasPermission(userRole, customPermissions = [], requiredPermission) {
  if (userRole === ROLES.SUPER_ADMIN) return true;

  const defaultRolePerms = ROLE_DEFAULT_PERMISSIONS[userRole] || [];
  if (defaultRolePerms.includes(requiredPermission)) {
    return true;
  }

  if (Array.isArray(customPermissions) && customPermissions.includes(requiredPermission)) {
    return true;
  }

  return false;
}
